import AppKit
import Combine
import SwiftUI

/// A short, private clipboard history for the Island: text only, in memory, never written to disk.
/// Password managers mark what they copy as concealed or transient; those are never recorded.
@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    @Published private(set) var items: [String] = []
    private var lastCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    func start() {
        guard timer == nil else { return }
        lastCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 1.0, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }

    func stop() { timer?.invalidate(); timer = nil }

    func clear() { items = [] }

    func remove(_ text: String) { items.removeAll { $0 == text } }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        if types.contains("org.nspasteboard.ConcealedType") || types.contains("org.nspasteboard.TransientType")
            || types.contains("org.nspasteboard.AutoGeneratedType") { return }
        guard let s = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !s.isEmpty, s.count < 20_000 else { return }
        items.removeAll { $0 == s }
        items.insert(s, at: 0)
        if items.count > 30 { items.removeLast(items.count - 30) }
    }
}

struct ClipboardPage: View {
    @ObservedObject private var history = ClipboardHistory.shared
    @State private var query = ""

    private var shown: [String] {
        let q = query.lowercased()
        return q.isEmpty ? history.items : history.items.filter { $0.lowercased().contains(q) }
    }

    var body: some View {
        VStack(spacing: 8) {
            HStack(spacing: 8) {
                Image(systemName: "magnifyingglass").font(.system(size: 11)).foregroundStyle(.white.opacity(0.5))
                TextField("Search clipboard", text: $query).textFieldStyle(.plain).font(.system(size: 12))
                Spacer()
                Button("Clear") { history.clear() }.buttonStyle(.plain).font(.system(size: 11)).foregroundStyle(.white.opacity(0.6))
            }
            if shown.isEmpty {
                Spacer()
                Text(history.items.isEmpty ? "Copy something and it shows up here." : "No matches").font(.system(size: 12)).foregroundStyle(.white.opacity(0.45))
                Spacer()
            } else {
                ScrollView {
                    VStack(spacing: 4) {
                        ForEach(shown, id: \.self) { text in
                            Button {
                                PasteService.copy(text)
                                PasteService.pasteIntoFront()
                            } label: {
                                HStack(spacing: 8) {
                                    Image(systemName: Self.kindSymbol(text)).font(.system(size: 10.5, weight: .semibold))
                                        .frame(width: 22, height: 22)
                                        .background(Circle().fill(.white.opacity(0.1)))
                                        .foregroundStyle(.white.opacity(0.75))
                                    Text(text.replacingOccurrences(of: "\n", with: " ")).font(.system(size: 11.5)).lineLimit(2)
                                    Spacer(minLength: 0)
                                    Image(systemName: "return").font(.system(size: 9, weight: .semibold)).foregroundStyle(.white.opacity(0.35))
                                }
                                    .frame(maxWidth: .infinity, alignment: .leading)
                                    .padding(.horizontal, 9).padding(.vertical, 5)
                                    .background(Color.white.opacity(0.08), in: RoundedRectangle(cornerRadius: 8, style: .continuous))
                            }
                            .buttonStyle(.plain)
                            .contextMenu {
                                Button("Copy") { PasteService.copy(text) }
                                Button("Pin") { PinStore.addText(text) }
                                Button("Remove") { history.remove(text) }
                            }
                        }
                    }
                }
                .scrollIndicators(.hidden)
            }
        }
        .foregroundStyle(.white)
        .padding(.vertical, 8)
    }

    /// What the clip looks like it is: a link, a colour, a path, code or text.
    static func kindSymbol(_ text: String) -> String {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if t.hasPrefix("http://") || t.hasPrefix("https://") { return "link" }
        if t.hasPrefix("#"), t.count == 7 || t.count == 4, t.dropFirst().allSatisfy(\.isHexDigit) { return "paintpalette" }
        if t.hasPrefix("/") || t.hasPrefix("~/") { return "folder" }
        if t.contains("{") || t.contains(";") || t.hasPrefix("$ ") || t.contains("()") { return "chevron.left.forwardslash.chevron.right" }
        if t.contains("@"), !t.contains(" "), t.contains(".") { return "envelope" }
        if Double(t.replacingOccurrences(of: ",", with: "")) != nil { return "number" }
        return "text.alignleft"
    }
}
